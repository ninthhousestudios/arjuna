/// Rank the seven embodied planets of every chart in a directory by
/// Lajjitaadi health, and emit a Markdown report.
///
/// Usage: dart run tool/bin/rank_planet_health.dart [options]
///   --charts `dir`     Directory of chart files (default:
///                      calc/test/charts)
///   --out `path`       Markdown output (default:
///                      docs/planet-health-results.md)
///   --ephe-path `dir`  Swiss Ephemeris data directory (.se1 + sefstars.txt).
///                      Defaults to $ARROW_EPHE_PATH, then libaditya/ephe,
///                      then left unset (SWE falls back to Moshier).
void main(List<String> args) {
  var chartsDir = 'calc/test/charts';
  var outPath = 'docs/planet-health-results.md';
  String? ephePath;

  for (var i = 0; i < args.length; i++) {
    if (args[i] == '--charts' && i + 1 < args.length) {
      chartsDir = args[++i];
    } else if (args[i] == '--out' && i + 1 < args.length) {
      outPath = args[++i];
    } else if (args[i] == '--ephe-path' && i + 1 < args.length) {
      ephePath = args[++i];
    }
  }
  ephePath ??= _findEphePath();

  final dir = Directory(chartsDir);
  if (!dir.existsSync()) {
    stderr.writeln('Charts directory not found: $chartsDir');
    exit(1);
  }

  final files =
      dir
          .listSync()
          .whereType<File>()
          .where(
            (f) => ChartIO.supportedExtensions.any(
              (ext) => f.path.toLowerCase().endsWith(ext),
            ),
          )
          .toList()
        ..sort((a, b) => a.path.compareTo(b.path));

  if (files.isEmpty) {
    stderr.writeln('No supported chart files in $chartsDir');
    exit(1);
  }

  const options = ArrowPresets.aditya;
  final facade = SweFacade.create(ephePath: ephePath);
  final out = StringBuffer();
  final stateTallies = <LajjitaadiState, int>{};
  final worstByChart = <String, BeingHealth>{};
  final bestByChart = <String, BeingHealth>{};

  out
    ..writeln('# Lajjitaadi planet-health ranking — test chart corpus')
    ..writeln()
    ..writeln(
      'Generated by `tool/bin/rank_planet_health.dart`. Algorithm and open '
      'questions: `docs/planet-health-ranking.md`.',
    )
    ..writeln()
    ..writeln(
      'Chart settings: ${_presetLabel()}. Ephemeris: '
      '${ephePath ?? 'Moshier (built-in)'}.',
    )
    ..writeln()
    ..writeln(
      'Ranking follows Laura\'s precedence rule: the **Strong** subtotal '
      '(dignity, sign, conjunction, shame) ranks a planet first, and the '
      '**Aspect** subtotal only breaks ties among planets it leaves level. '
      '**Total** = Strong + Aspect is shown for reference, but a lower total '
      'can still rank higher when its strong subtotal wins.',
    )
    ..writeln();

  for (final file in files) {
    final data = ChartIO.read(file.path);
    final utc = _utcDateTime(data);
    final snapshot = facade.calcAll(
      julianDay(utc),
      Location(
        latitude: data.birthLocation.latitude,
        longitude: data.birthLocation.longitude,
      ),
      options.sweConfig,
    );
    final chart = Chart(snapshot, options.calcConfig);
    final ranked = PlanetHealth.rank(chart.rashi);

    for (final r in ranked) {
      for (final state in r.score.states) {
        stateTallies[state] = (stateTallies[state] ?? 0) + 1;
      }
    }
    bestByChart[data.name] = ranked.first;
    worstByChart[data.name] = ranked.last;

    _writeChart(out, data, utc, ranked);
  }

  facade.dispose();

  _writeSummary(out, files.length, stateTallies, bestByChart, worstByChart);

  final report = out.toString();
  File(outPath)
    ..parent.createSync(recursive: true)
    ..writeAsStringSync(report);
  stdout.writeln(report);
  stderr.writeln('\nWritten to $outPath (${files.length} charts)');
}

void _writeChart(
  StringBuffer out,
  ChartData data,
  DateTime utc,
  List<BeingHealth> ranked,
) {
  final loc = data.birthLocation;
  out
    ..writeln('---')
    ..writeln()
    ..writeln('## ${data.name}')
    ..writeln()
    ..writeln(
      '- Birth: ${_formatLocal(data.dateTime)} local '
      '(UTC${_formatOffset(data.utcOffsetHours + data.dstOffsetHours)}) '
      '= ${_formatLocal(utc)} UT',
    )
    ..writeln(
      '- Place: ${loc.city}${loc.country.isEmpty ? '' : ', ${loc.country}'} '
      '(${loc.latitude.toStringAsFixed(4)}, '
      '${loc.longitude.toStringAsFixed(4)})',
    )
    ..writeln()
    ..writeln(
      '| # | Planet | Strong | Aspect | Total | Aditya | Hora | '
      'Trimsamsa being | Hora being | Avasthas |',
    )
    ..writeln(
      '|---|----|------:|------:|------:|----|------|---------|------|----|',
    );
  for (final r in ranked) {
    out.writeln(
      '| ${r.rank} '
      '| ${_title(r.body.name)} '
      '| ${_v(r.score.strongVirupas)} '
      '| ${_v(r.score.aspectVirupas)} '
      '| ${_v(r.virupas)} '
      '| ${r.aditya.name} '
      '| ${r.hora == Hora.sun ? 'Sun' : 'Moon'} '
      '| ${r.trimsamsaBeing.name} (${_title(r.trimsamsaBeing.type.name)}) '
      '| ${r.horaBeing.name} (${_title(r.horaBeing.type.name)}) '
      '| ${_statesSummary(r.score)} |',
    );
  }
  out
    ..writeln()
    ..writeln('<details><summary>Factor breakdown</summary>')
    ..writeln();
  for (final r in ranked) {
    out
      ..writeln('**${_title(r.body.name)}** — ${_v(r.virupas)}v')
      ..writeln();
    if (r.score.factors.isEmpty) {
      out.writeln('- (no avasthas)');
    }
    for (final f in r.score.factors) {
      out.writeln('- ${_factorLine(f)}');
    }
    out.writeln();
  }
  out
    ..writeln('</details>')
    ..writeln();
}

String _factorLine(ScoredFactor f) {
  final cause = StringBuffer(f.factor.source);
  if (f.factor.planet != null) cause.write(' ${_title(f.factor.planet!.name)}');
  if (f.factor.lord != null) {
    cause.write(' lord ${_title(f.factor.lord!.name)}');
  }
  if (f.factor.dignity != null) cause.write(' ${f.factor.dignity}');
  if (f.factor.detail != null) cause.write(' — ${f.factor.detail}');
  return '`${f.state.libadityaName}` via $cause '
      '@ ${_v(f.strength)}/60 → **${_v(f.virupas)}v**';
}

String _statesSummary(PlanetHealthScore score) {
  final entries = score.byState.entries.toList()
    ..sort((a, b) => a.value.compareTo(b.value));
  return entries.map((e) => '${e.key.libadityaName} ${_v(e.value)}').join(', ');
}

void _writeSummary(
  StringBuffer out,
  int chartCount,
  Map<LajjitaadiState, int> stateTallies,
  Map<String, BeingHealth> best,
  Map<String, BeingHealth> worst,
) {
  out
    ..writeln('---')
    ..writeln()
    ..writeln('## Corpus summary')
    ..writeln()
    ..writeln('$chartCount charts, ${chartCount * 7} planets.')
    ..writeln()
    ..writeln('### Avastha frequency (planets carrying the state at all)')
    ..writeln()
    ..writeln('| State | Planets | % of planets |')
    ..writeln('|-------|--------:|-------------:|');
  final total = chartCount * 7;
  final ordered = LajjitaadiState.values.toList()
    ..sort((a, b) => (stateTallies[b] ?? 0).compareTo(stateTallies[a] ?? 0));
  for (final state in ordered) {
    final n = stateTallies[state] ?? 0;
    out.writeln(
      '| ${state.libadityaName} | $n | '
      '${(100 * n / total).toStringAsFixed(0)}% |',
    );
  }
  out
    ..writeln()
    ..writeln('### Healthiest and least healthy planet per chart')
    ..writeln()
    ..writeln(
      '| Chart | Healthiest | Virupas | Its being | '
      'Least healthy | Virupas | Its being |',
    )
    ..writeln('|-------|-----------|--------:|-----|----|--------:|----|');
  for (final name in best.keys) {
    final b = best[name]!;
    final w = worst[name]!;
    out.writeln(
      '| $name '
      '| ${_title(b.body.name)} | ${_v(b.virupas)} '
      '| ${b.trimsamsaBeing.name} / ${b.horaBeing.name} '
      '| ${_title(w.body.name)} | ${_v(w.virupas)} '
      '| ${w.trimsamsaBeing.name} / ${w.horaBeing.name} |',
    );
  }
  out.writeln();
}

/// [ChartData.utcDateTime] returns a local-kind [DateTime], which
/// [julianDay] would then shift again by the machine's timezone. Rebuild
/// the same instant with a UTC kind.
DateTime _utcDateTime(ChartData data) {
  final local = data.dateTime;
  return DateTime.utc(
    local.year,
    local.month,
    local.day,
    local.hour,
    local.minute,
    local.second,
  ).subtract(
    Duration(
      minutes: ((data.utcOffsetHours + data.dstOffsetHours) * 60).round(),
    ),
  );
}

String _presetLabel() {
  const c = ArrowPresets.aditya;
  return 'circle=${c.calcConfig.circle.name}, '
      'sign ayanamsa=${c.sweConfig.signAyanamsa.name}, '
      'houses=${c.sweConfig.houseSystem.name}';
}

String _v(double value) => value.toStringAsFixed(1);

String _title(String s) => s[0].toUpperCase() + s.substring(1);

String _formatLocal(DateTime dt) =>
    '${dt.year}-${_p2(dt.month)}-${_p2(dt.day)} '
    '${_p2(dt.hour)}:${_p2(dt.minute)}';

String _p2(int n) => n.toString().padLeft(2, '0');

String _formatOffset(double hours) {
  final sign = hours < 0 ? '-' : '+';
  final abs = hours.abs();
  final h = abs.floor();
  final m = ((abs - h) * 60).round();
  return '$sign${_p2(h)}:${_p2(m)}';
}

/// Search common locations for the Swiss Ephemeris data directory.
String? _findEphePath() {
  final env = Platform.environment['ARROW_EPHE_PATH'];
  if (env != null && Directory(env).existsSync()) return env;

  final home = Platform.environment['HOME'] ?? '';
  final candidates = [
    '$home/nhs/soft/astrology/libaditya/libaditya/ephe',
    '$home/.arrow/ephe',
    '/usr/local/share/swisseph',
  ];
  for (final path in candidates) {
    if (Directory(path).existsSync()) return path;
  }
  return null;
}
